"use server";

import { stripe } from "@/lib/stripe";
import { env } from "@/lib/env";

export async function checkStripeConnection() {
    const results = {
        envMock: false,
        apiKeyConfigured: false,
        stripeConnection: false,
        webhookSecretConfigured: false,
        webhookSecretSample: "",
        productList: 0,
        error: null as string | null,
    };

    try {
        // 1. Check Env Vars availability (safe check)
        if (env.STRIPE_SECRET_KEY && (env.STRIPE_SECRET_KEY.startsWith("sk_") || env.STRIPE_SECRET_KEY.startsWith("rk_"))) {
            results.apiKeyConfigured = true;
        }

        if (env.STRIPE_WEBHOOK_SECRET && env.STRIPE_WEBHOOK_SECRET.startsWith("whsec_")) {
            results.webhookSecretConfigured = true;
            results.webhookSecretSample = env.STRIPE_WEBHOOK_SECRET.substring(0, 8) + "...";
        }

        // 2. Test Connection
        const products = await stripe.products.list({ limit: 3 });
        results.stripeConnection = true;
        results.productList = products.data.length;

        return { success: true, data: results };
        // eslint-disable-next-line @typescript-eslint/no-explicit-any
    } catch (error: any) {
        console.error("Stripe Test Failed:", error);
        return {
            success: false,
            data: results,
            message: error.message || "Unknown error occurred"
        };
    }
}

export async function seedStripeProduct() {
    try {
        const product = await stripe.products.create({
            name: "Test Product " + new Date().toISOString(),
            description: "Generated by Stripe Diagnostics",
        });

        const price = await stripe.prices.create({
            product: product.id,
            unit_amount: 1000, // $10.00
            currency: 'usd',
        });

        return {
            success: true,
            product: JSON.parse(JSON.stringify(product)),
            price: JSON.parse(JSON.stringify(price))
        };
        // eslint-disable-next-line @typescript-eslint/no-explicit-any
    } catch (error: any) {
        return { success: false, message: error.message };
    }
}
